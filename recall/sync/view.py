"""The readable side of the card repository: the current cards as markdown, one file per project.

Generated from the merged event logs on every sync and never read back. The output depends
only on the cards, so a sync that changes nothing produces no commit.
"""
import collections
import os
import re
import shutil

from ..core import keys
from ..write.extract import display

NOTE = "Generated by the recall sync from the event logs in `events/`. Do not edit: the next sync overwrites it."


def _group(card, known):
    """General cards share one file; project cards go to their project on any device."""
    if card.get("scope") == "general":
        return None
    proj = keys.portable(card.get("project", ""), known)
    return display(card.get("project", "")) if proj not in ("", "-") else "no project"


def _block(card):
    seen = f", seen {card['count']} times" if card.get("count", 1) > 1 else ""
    meta = ", ".join(x for x in (card.get("date", ""), card.get("kind", ""), display(card.get("project", "")),
                                 card.get("device", "")) if x)
    return (f"### {card['referent']}\n\n{card['lesson']}\n\nApplies when: {card['trigger']}\n\n"
            f"`{card['id']}` {meta}{seen}\n")


def _page(title, cards):
    body = "\n".join(_block(c) for c in sorted(cards, key=lambda c: (c.get("date", ""), c["id"]), reverse=True))
    return f"# {title}\n\n{NOTE}\n\n{len(cards)} cards, newest first.\n\n{body}"


def _slug(name):
    return re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip("-") or "unnamed"


def render(cards, known):
    """{path relative to the branch root: text} for the active cards."""
    live = [c for c in cards.values() if c["status"] == "active"]
    groups = collections.defaultdict(list)
    for card in live:
        groups[_group(card, known)].append(card)
    files = {"cards/general.md": _page("General lessons", groups.pop(None, []))}
    rows = [f"| [General](general.md) | {sum(c.get('scope') == 'general' for c in live)} |"]
    for name in sorted(groups):
        files[f"cards/projects/{_slug(name)}.md"] = _page(name, groups[name])
        rows.append(f"| [{name}](projects/{_slug(name)}.md) | {len(groups[name])} |")
    by_device = collections.Counter(c.get("device", "") or "unknown" for c in live)
    devices = "\n".join(f"| {d} | {n} |" for d, n in sorted(by_device.items()))
    files["cards/index.md"] = (
        f"# Lesson cards\n\n{NOTE}\n\n{len(live)} active cards, {len(cards) - len(live)} superseded.\n\n"
        f"| Where | Active cards |\n|---|---|\n" + "\n".join(rows) +
        f"\n\n| Written on | Active cards |\n|---|---|\n{devices}\n")
    return files


def write(root, cards, known):
    shutil.rmtree(os.path.join(root, "cards"), ignore_errors=True)
    for rel, text in render(cards, known).items():
        path = os.path.join(root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
